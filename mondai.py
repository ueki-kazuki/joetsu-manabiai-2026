# もんだい：このプログラムには3つのバグ（まちがい）があります。
# ゲームをうごかして、へんなところをみつけて、なおしてみよう！
#
# ヒント：
# 1. さゆうキーをおしても、じぶんがうごかない → 「自機の動き」の関数をみてみよう
# 2. たまが てきに あたっても、てきが きえない（すりぬける）→ 「たまの当たり判定」の関数をみてみよう
# 3. てきに ぶつかっても、ゲームオーバーにならない → 「敵との当たり判定」の関数をみてみよう

import pygame
from pygame.locals import QUIT, KEYDOWN, K_ESCAPE, MOUSEBUTTONDOWN, Rect
import random
import os


def main():
    (がめんはば, がめんたかさ) = (500, 1024)  # 画面サイズ
    (よこ, たて) = (150, 150)  # 初期位置
    (よこ, たて) = (150, がめんたかさ - たて)  # 初期位置
    (はば, たかさ) = (30, 30)  # プレイヤーのはばと高さ
    fps = 30  # 画面をかきかえる速さ（フレームレート）
    たまのならび = []  # たまを管理用のリスト
    (いどうそくど, たまのそくど, てきのそくど) = (10, 10, 10)  # 移動速度（たま）と敵
    カウンタ = 0  # カウンタ（敵の出現管理）
    てきのでにくさ = 50  # 敵の出現間かく
    とくてん = 0  # とくてん
    ゲームオーバー = False  # ゲームオーバーかどうか
    がぞうモード = False  # 画像で表示するかどうか
    がぞうフォルダ = os.path.join(
        os.path.dirname(os.path.abspath(__file__)), "images"
    )  # 画像の場所

    # しょりかいし
    # がめんをしょきかする
    pygame.init()  # ライブラリの初期化
    まど = pygame.Window(
        "スーパーシューティング（もんだい）", size=(がめんはば, がめんたかさ)
    )  # ウインドウの作成
    まど.focus()  # ウインドウを他より前に出す
    がめん = まど.get_surface()  # 画面のサーフェスを取得

    じぶん = Rect(よこ, たて, はば, たかさ)  # 四角形（プレイヤー）
    じぶんのいろ = (255, 0, 0)  # 色の設定（赤）
    とけい = pygame.time.Clock()  # 時間管理用オブジェクトの作成
    てきたち = [
        Rect(random.randrange(0, がめんはば - はば + 1), 0, はば, たかさ)
    ]  # 敵を管理用のリスト
    てきのいろ = (0, 0, 255)  # 色の設定（青）
    たまのおおきさ = 10  # たまの大きさ
    たまのかんかく = 10  # たまを出せる間かく（フレーム数）
    たまのカウンタ = 0  # 前のたまからの経過フレーム数
    じぶんのがぞう = pygame.image.load(
        os.path.join(がぞうフォルダ, "player.png")
    ).convert_alpha()  # 自機の画像
    てきのがぞう = pygame.image.load(
        os.path.join(がぞうフォルダ, "enemy.png")
    ).convert_alpha()  # 敵の画像
    たまのがぞう = pygame.image.load(
        os.path.join(がぞうフォルダ, "bullet.png")
    ).convert_alpha()  # たまの画像
    フォント = pygame.font.Font(None, 40)  # もじの表示用

    def 自機の動き(pressed_keys):  # プレイヤーの左右移動と画面のはしの制限
        if pressed_keys[pygame.K_LEFT]:  # 左矢印キーがおされた場合
            pass  # じぶん.move_ip(-いどうそくど, 0)
        elif pressed_keys[pygame.K_RIGHT]:  # 右矢印キーがおされた場合
            pass  # じぶん.move_ip(いどうそくど, 0)
        if じぶん.x < 0:  # 左はしより外に出た場合
            じぶん.x = 0
        elif じぶん.x > がめんはば - はば:  # 右はしより外に出た場合
            じぶん.x = がめんはば - はば

    def たまの当たり判定(たま):  # たまが敵にあたったかどうかを判定する
        nonlocal とくてん
        # for j, てき in enumerate(てきたち):  # 敵の数だけくり返し
        #     if (
        #         てき.x <= たま.x <= てき.x + はば
        #         and てき.y <= たま.y <= てき.y + たかさ
        #     ):
        #         てきたち.pop(j)  # 敵を消す
        #         とくてん += 10  # とくてん加算
        #         return True
        return False

    def たまの動き():  # たまを動かして、かいて、消す
        for i, たま in enumerate(たまのならび):  # たまの数だけくり返し
            たま.move_ip(0, -たまのそくど)  # たまの移動
            if がぞうモード:  # 画像で表示する場合
                がめん.blit(たまのがぞう, たま)  # 画像（たま）
            else:
                pygame.draw.circle(
                    がめん, (0, 255, 0), (たま.x, たま.y), たま.w / 2
                )  # たまをかく
            たまがあたった = たまの当たり判定(たま)  # たまが敵にあたったかどうか
            if たま.y < 0 or たまがあたった:  # たまが画面外に出たか敵にあたった場合
                たまのならび.pop(i)  # たまを消す

    def 敵との当たり判定(てき):  # 自機と敵があたったかどうかを判定する
        nonlocal ゲームオーバー
        if じぶん.colliderect(てき):  # 自機に敵があたった場合
            pass  # ゲームオーバー = True
            return True
        return False

    def たまを出す(x, y):  # 指定した位置からたまを1つ出す
        たまのならび.append(Rect(x, y, たまのおおきさ, たまのおおきさ))

    # ゲームのメインループ
    while True:  # メインループ
        がめん.fill((0, 0, 0))  # 黒でぬりつぶす
        if がぞうモード:  # 画像で表示する場合
            がめん.blit(じぶんのがぞう, じぶん)  # 画像（プレイヤー）
        else:
            pygame.draw.rect(がめん, じぶんのいろ, じぶん)  # 四角形（プレイヤー）

        if not ゲームオーバー:  # ゲームオーバーでない場合だけ動かす
            たまの動き()

            for i, てき in enumerate(てきたち):  # 敵の数だけくり返し
                てき.move_ip(0, てきのそくど)  # 敵の移動
                if がぞうモード:  # 画像で表示する場合
                    がめん.blit(てきのがぞう, てき)  # 画像（敵）
                else:
                    pygame.draw.rect(がめん, てきのいろ, てき)  # 敵をかく
                あたった = 敵との当たり判定(てき)  # 自機に敵があたったかどうか
                if not あたった and てき.y > がめんたかさ:  # 敵が画面外に出た場合
                    てきたち.pop(i)  # 敵を消す

            カウンタ += 1  # カウンタ増加
            if カウンタ > てきのでにくさ:  # 出現間かくチェック
                てきたち.append(
                    Rect(random.randrange(0, がめんはば - はば + 1), 0, はば, たかさ)
                )  # 敵生成
                カウンタ = 0  # カウンタ初期化

        とくてんもじ = フォント.render(
            f"SCORE {とくてん}", True, (255, 255, 255)
        )  # とくてんの表示
        がめん.blit(とくてんもじ, (10, 10))
        if ゲームオーバー:  # ゲームオーバーの場合
            ゲームオーバーもじ = フォント.render("GAME OVER", True, (255, 255, 255))
            がめん.blit(
                ゲームオーバーもじ,
                ゲームオーバーもじ.get_rect(
                    center=(がめんはば // 2, がめんたかさ // 2)
                ),
            )
            あんないもじ = フォント.render(
                "PRESS ENTER TO RESTART", True, (255, 255, 255)
            )  # あんないの表示
            がめん.blit(
                あんないもじ,
                あんないもじ.get_rect(center=(がめんはば // 2, がめんたかさ // 2 + 40)),
            )

        まど.flip()  # 画面をかきかえる

        とけい.tick(fps)  # FPSの設定
        if not ゲームオーバー:  # ゲームオーバーでない場合だけ動かす
            たまのカウンタ += 1  # カウンタ増加
            pressed_keys = pygame.key.get_pressed()
            自機の動き(pressed_keys)
            if (
                pressed_keys[pygame.K_SPACE] and たまのカウンタ >= たまのかんかく
            ):  # スペースキーがおされた場合
                たまを出す(じぶん.x + はば / 2, じぶん.y)
                たまのカウンタ = 0  # カウンタ初期化

        for イベント in pygame.event.get():  # イベントをチェックするくり返し
            if イベント.type == QUIT:  # ウインドウがとじられた場合
                return
            elif (
                イベント.type == KEYDOWN and イベント.key == K_ESCAPE
            ):  # エスケープキーがおされた場合
                return
            elif (
                イベント.type == KEYDOWN and イベント.key == pygame.K_i
            ):  # 「い」キーがおされた場合
                がぞうモード = not がぞうモード  # 画像で表示するかどうかを切りかえる
            elif (
                イベント.type == KEYDOWN
                and イベント.key == pygame.K_RETURN
                and ゲームオーバー
            ):  # ゲームオーバー中にエンターキーがおされた場合
                じぶん = Rect(よこ, たて, はば, たかさ)  # 自機をもとの位置にもどす
                たまのならび = []  # たまを消す
                てきたち = [
                    Rect(random.randrange(0, がめんはば - はば + 1), 0, はば, たかさ)
                ]  # 敵をもとにもどす
                カウンタ = 0  # カウンタをもとにもどす
                とくてん = 0  # とくてんをもとにもどす
                たまのカウンタ = 0  # たまのカウンタをもとにもどす
                ゲームオーバー = False  # ゲームオーバーをかいじょ
            elif (
                イベント.type == MOUSEBUTTONDOWN
                and イベント.button == 1
                and not ゲームオーバー
            ):  # マウスをクリックした場合
                cx, cy = イベント.pos  # クリック時のマウスの位置を取得
                cx += はば / 2
                たまを出す(cx, cy)  # まっすぐ上のたま


if __name__ == "__main__":
    main()
