# もんだい（こたえ）：3つのバグを ぜんぶ なおした バージョンです。

import pygame
from pygame.locals import QUIT, KEYDOWN, K_ESCAPE, Rect
import random
import os


def main():
    (がめんはば, がめんたかさ) = (500, 700)  # 画面の大きさ
    よこ = 150  # じぶんのよこ位置
    たて = がめんたかさ - 150  # じぶんのたて位置
    (はば, たかさ) = (48, 48)  # じぶんの はばと たかさ
    fps = 30  # 画面をかきかえる速さ
    たまのならび = []  # たまを管理するリスト
    いどうそくど = 10  # じぶんの移動の速さ
    たまのそくど = 10  # たまの移動の速さ
    てきのそくど = 7  # てきの移動の速さ
    カウンタ = 0  # てきが出るまで数える
    てきのでにくさ = 50  # てきが出るまでの間かく
    とくてん = 0  # とくてん
    ゲームオーバー = False  # ゲームオーバーかどうか
    がぞうモード = False  # 画像で表示するかどうか
    がぞうフォルダ = os.path.join(
        os.path.dirname(os.path.abspath(__file__)), "images"
    )  # 画像の場所

    # しょりかいし
    # がめんをしょきかする
    pygame.init()  # pygameの準備
    まど = pygame.Window(
        "超絶怒涛シューティング（こたえ）", size=(がめんはば, がめんたかさ)
    )  # ウインドウの作成
    まど.focus()  # ウインドウを他より前に出す
    がめん = まど.get_surface()  # 画面のサーフェスを取得

    じぶん = Rect(よこ, たて, はば, たかさ)  # じぶんの四角形
    じぶんのいろ = (255, 0, 0)  # 色の設定（赤）
    とけい = pygame.time.Clock()  # 時間管理用オブジェクトの作成
    てきたち = [
        Rect(random.randrange(0, がめんはば - はば + 1), 0, はば, たかさ)
    ]  # てきを管理するリスト
    てきのいろ = (0, 0, 255)  # 色の設定（青）
    たまのおおきさ = 48  # たまの大きさ
    たまのかんかく = 10  # たまを出せる間かく（画面を書きかえる回数）
    たまのカウンタ = 0  # 前のたまから何回書きかえたか
    たまのよこそくど = 5  # ななめのたまがよこに進む速さ
    じぶんのがぞう = pygame.image.load(
        os.path.join(がぞうフォルダ, "player.png")
    ).convert_alpha()  # じぶんの絵
    てきのがぞう = pygame.image.load(
        os.path.join(がぞうフォルダ, "enemy.png")
    ).convert_alpha()  # てきの絵
    たまのがぞう = pygame.image.load(
        os.path.join(がぞうフォルダ, "bullet.png")
    ).convert_alpha()  # たまの絵
    フォント = pygame.font.Font(None, 40)  # もじの表示用

    def じぶんの動き(おされているキー):  # じぶんを左右に動かす
        if おされているキー[pygame.K_LEFT]:  # 左矢印キーが押された場合
            じぶん.move_ip(-いどうそくど, 0)
        elif おされているキー[pygame.K_RIGHT]:  # 右矢印キーが押された場合
            じぶん.move_ip(いどうそくど, 0)
        if じぶん.x < 0:  # 左はしより外に出た場合
            じぶん.x = 0
        elif じぶん.x > がめんはば - はば:  # 右はしより外に出た場合
            じぶん.x = がめんはば - はば

    def たまが敵に当たったか(たま):  # たまが敵に当たったか調べる
        nonlocal とくてん
        for てき in てきたち:
            if たま.colliderect(てき):
                てきたち.remove(てき)
                とくてん += 10
                return True
        return False

    def たまの動き():  # たまを動かして、かいて、消す
        for たま in たまのならび.copy():  # たまを1つずつ調べる
            しかく = たま[0]  # たまの四角形
            たまのよこ = たま[1]  # たまのよこ方向の速さ
            しかく.move_ip(たまのよこ, -たまのそくど)  # たまを動かす
            if がぞうモード:  # 画像で表示する場合
                がめん.blit(たまのがぞう, しかく)  # 画像（たま）
            else:
                pygame.draw.circle(
                    がめん,
                    (0, 255, 0),
                    しかく.center,
                    しかく.w / 2,
                )  # たまをかく
            たまがあたった = たまが敵に当たったか(しかく)
            if しかく.y < 0 or たまがあたった:  # たまが画面外か敵に当たった場合
                たまのならび.remove(たま)  # たまを消す

    def たまを出す(x, y, よこ):  # 指定した位置からたまを1つ出す
        たまのならび.append(
            [
                Rect(
                    x - たまのおおきさ / 2,
                    y - たまのおおきさ,
                    たまのおおきさ,
                    たまのおおきさ,
                ),
                よこ,
            ]
        )

    # ゲームのメインループ
    while True:  # メインループ
        がめん.fill((0, 0, 0))  # 黒で塗りつぶす
        if がぞうモード:  # 画像で表示する場合
            がめん.blit(じぶんのがぞう, じぶん)  # 画像（プレイヤー）
        else:
            pygame.draw.rect(がめん, じぶんのいろ, じぶん)  # 四角形（プレイヤー）

        if not ゲームオーバー:  # ゲームオーバーでない場合だけ動かす
            たまの動き()

            for てき in てきたち.copy():  # てきを1つずつ調べる
                てき.move_ip(0, てきのそくど)  # てきを動かす
                if がぞうモード:  # 画像で表示する場合
                    がめん.blit(てきのがぞう, てき)  # 画像（敵）
                else:
                    pygame.draw.rect(がめん, てきのいろ, てき)  # てきをかく
                if じぶん.colliderect(てき):
                    ゲームオーバー = True
                if てき.y > がめんたかさ:  # 敵が画面外に出た場合
                    てきたち.remove(てき)  # てきを消す

            カウンタ += 1  # カウンタ増加
            if カウンタ > てきのでにくさ:  # てきを出す間かくのチェック
                てきたち.append(
                    Rect(random.randrange(0, がめんはば - はば + 1), 0, はば, たかさ)
                )  # てきを出す
                カウンタ = 0  # カウンタを0にもどす

        とくてんもじ = フォント.render(
            f"SCORE {とくてん}", True, (255, 255, 255)
        )  # とくてんの表示
        がめん.blit(とくてんもじ, (10, 10))
        if ゲームオーバー:  # ゲームオーバーの場合
            ゲームオーバーもじ = フォント.render("GAME OVER", True, (255, 255, 255))
            がめん.blit(
                ゲームオーバーもじ,
                ゲームオーバーもじ.get_rect(
                    center=(がめんはば // 2, がめんたかさ // 2)
                ),
            )
            あんないもじ = フォント.render(
                "PRESS ENTER TO RESTART", True, (255, 255, 255)
            )  # あんないの表示
            がめん.blit(
                あんないもじ,
                あんないもじ.get_rect(center=(がめんはば // 2, がめんたかさ // 2 + 40)),
            )

        まど.flip()  # 画面をかきかえる

        とけい.tick(fps)  # FPSの設定
        if not ゲームオーバー:  # ゲームオーバーでない場合だけ動かす
            たまのカウンタ += 1  # カウンタ増加
            おされているキー = pygame.key.get_pressed()
            じぶんの動き(おされているキー)
            if (
                おされているキー[pygame.K_SPACE]
                and たまのカウンタ >= たまのかんかく
            ):  # スペースキーが押された場合
                まんなか = じぶん.x + はば / 2  # じぶんのまんなか
                たまを出す(まんなか, じぶん.y, 0)  # まっすぐ上のたま
                たまを出す(まんなか, じぶん.y, たまのよこそくど)  # 右ななめ上
                たまを出す(まんなか, じぶん.y, -たまのよこそくど)  # 左ななめ上
                たまのカウンタ = 0  # カウンタを0にもどす

        for イベント in pygame.event.get():  # イベント処理用の繰り返し
            if イベント.type == QUIT:  # ウインドウが閉じられた場合
                return
            elif (
                イベント.type == KEYDOWN and イベント.key == K_ESCAPE
            ):  # エスケープキーが押された場合
                return
            elif (
                イベント.type == KEYDOWN and イベント.key == pygame.K_i
            ):  # 「い」キーが押された場合
                がぞうモード = not がぞうモード  # 画像で表示するかどうかを切りかえる
            elif (
                イベント.type == KEYDOWN
                and イベント.key == pygame.K_RETURN
                and ゲームオーバー
            ):  # ゲームオーバー中にエンターキーが押された場合
                じぶん = Rect(よこ, たて, はば, たかさ)  # じぶんをもとの位置にもどす
                たまのならび = []  # たまを消す
                てきたち = [
                    Rect(random.randrange(0, がめんはば - はば + 1), 0, はば, たかさ)
                ]  # てきをもとにもどす
                カウンタ = 0  # カウンタをもとにもどす
                とくてん = 0  # とくてんをもとにもどす
                たまのカウンタ = 0  # たまのカウンタをもとにもどす
                ゲームオーバー = False  # ゲームオーバーをかいじょ


if __name__ == "__main__":
    main()
